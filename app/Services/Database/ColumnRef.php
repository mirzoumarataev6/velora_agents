<?php

namespace App\Services\Database;

/**
 * One column, and which table in the query it belongs to.
 *
 * Before joins there was no question to answer: every column in a search came
 * from the one product table, so a bare name identified it. With a category
 * table alongside, `name` could mean two different columns — and resolving that
 * by parsing "categories.name" out of a string would put string-splitting
 * between a caller's intent and the SQL, which is exactly where identifier bugs
 * live.
 *
 * So a reference is a pair, always. An empty alias means the product table
 * itself; anything else is a join's alias, and a join's alias is generated by us
 * (`j0`, `j1`) rather than taken from the customer's schema.
 */
final class ColumnRef
{
    public function __construct(
        public readonly string $column,
        public readonly string $alias = '',
    ) {}

    /**
     * Accept the shapes a caller may already have.
     *
     * A plain string is the product table's own column, which is what every
     * caller wrote before joins existed and what most still write.
     *
     * @param  self|array{column?: string, alias?: string}|string  $value
     */
    public static function make(self|array|string $value): self
    {
        if ($value instanceof self) {
            return $value;
        }

        if (is_string($value)) {
            return new self($value);
        }

        return new self(
            column: (string) ($value['column'] ?? ''),
            alias: (string) ($value['alias'] ?? ''),
        );
    }

    /**
     * The identity used for closed-set membership: two references match only
     * when both the column AND the table it came from match.
     */
    public function key(): string
    {
        return $this->alias.'.'.$this->column;
    }

    public function isBase(): bool
    {
        return $this->alias === '';
    }
}
